                    <div id="profile-copy">
                                   <p>Scott Forstall is senior vice president of iPhone Software at Apple. Reporting directly to the CEO, Forstall leads the team responsible for delivering the software at the heart of Apple’s revolutionary iPhone including the user interface, applications, frameworks and the operating system.</p>
<p>Forstall joined Apple in 1997 and is one of the original architects of Mac OS X and its Aqua user interface. He was responsible for several releases of the operating system, most notably Mac OS X Leopard. Prior to Apple he worked at NeXT developing core technologies.</p>
<p>Forstall received both a Bachelor of Science in Symbolic Systems and a Master of Science in Computer Science from Stanford University.</p>
